import { readFileSync } from 'node:fs';
import { advanceTo, createEcosystem, liveStandings } from '../../src/core/competition/ecosystem';
import { quickResolver } from '../../src/core/competition/quickResolver';
import { dayOf } from '../../src/core/world/calendar';
import { generateWorld } from '../../src/core/world/generate';
const f = JSON.parse(readFileSync('src/shared/art/world.json', 'utf8'));
const w = generateWorld({ seed: 'apex-world-1', featured: { teams: f.teams, players: f.players, coaches: f.coaches } });
const eco = createEcosystem(w, quickResolver(w, 'x'), dayOf(0, 0, 1) - 1);
advanceTo(eco, dayOf(1, 6, 1));
const st = liveStandings(eco, w.day);
const top16 = new Set(st.slice(0, 16).map((s) => s.orgId));
const all = [...w.players.values()].filter((p) => !p.retired);
const ros = all.filter((p) => p.orgId);
const q = (xs: number[], p: number) => { const s = [...xs].sort((a, b) => a - b); return s[Math.floor(p * (s.length - 1))]!.toFixed(1); };
const sk = (xs: typeof all) => xs.map((p) => p.skill);
console.log('all', all.length, 'p10', q(sk(all), .1), 'p50', q(sk(all), .5), 'p90', q(sk(all), .9), 'p99', q(sk(all), .99), 'max', q(sk(all), 1));
console.log('rostered', ros.length, 'p50', q(sk(ros), .5), 'p90', q(sk(ros), .9));
const t1 = ros.filter((p) => top16.has(p.orgId!));
console.log('top16 starters', t1.length, 'min', q(sk(t1), 0), 'p10', q(sk(t1), .1), 'p50', q(sk(t1), .5), 'max', q(sk(t1), 1));
console.log('top 10 players', [...ros].sort((a, b) => b.skill - a.skill).slice(0, 10).map((p) => p.skill.toFixed(1)).join(' '));
import { toOvr } from '../../src/core/world/ratings';
const ov = (xs: typeof all) => xs.map((p) => toOvr(p.skill));
console.log('OVR top16 starters: share>=80', (t1.filter((p) => toOvr(p.skill) >= 80).length / t1.length).toFixed(2), 'median', q(ov(t1), .5), '| all >=90:', all.filter((p) => toOvr(p.skill) >= 90).length, ' 99:', all.filter((p) => toOvr(p.skill) >= 99).length, '| rostered median', q(ov(ros), .5), 'FA median', q(ov(all.filter((p) => !p.orgId)), .5));
