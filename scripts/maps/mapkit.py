"""Map authoring kit: compose tile layouts from rectangles/props and render previews.

Layouts are 80x60 tiles (2 m each). Output is a TypeScript module exporting the
layout rows. Spots/callouts/strategy are authored by hand in the map's .ts file.
"""
from PIL import Image, ImageDraw

COLORS = {
    '#': (14, 18, 24), '~': (24, 64, 92), '.': (96, 104, 112), ',': (66, 72, 80), '=': (122, 92, 60),
    '-': (90, 108, 124), ':': (112, 104, 88), '"': (70, 100, 60), '_': (140, 136, 128), 's': (130, 130, 140),
    'r': (84, 80, 76), 'A': (150, 120, 70), 'B': (150, 120, 70), 'T': (130, 80, 60), 'C': (60, 90, 130),
    'O': (170, 70, 50), 'o': (150, 120, 80), 'p': (40, 44, 50), 'v': (60, 70, 90), 'x': (176, 150, 100),
    'h': (190, 190, 190), 'w': (140, 200, 230),
}


class Canvas:
    def __init__(self, cols=80, rows=60, fill='#'):
        self.cols, self.rows = cols, rows
        self.g = [[fill] * cols for _ in range(rows)]

    def rect(self, x0, y0, x1, y1, ch):
        for y in range(min(y0, y1), max(y0, y1) + 1):
            for x in range(min(x0, x1), max(x0, x1) + 1):
                if 0 <= x < self.cols and 0 <= y < self.rows:
                    self.g[y][x] = ch

    def put(self, x, y, ch):
        self.g[y][x] = ch

    def points(self, pts, ch):
        for x, y in pts:
            self.put(x, y, ch)

    def get(self, x, y):
        return self.g[y][x]

    def rows_str(self):
        return [''.join(r) for r in self.g]

    def write_ts(self, path, const):
        rows = self.rows_str()
        body = ',\n'.join(f"  '{r}'" for r in rows)
        with open(path, 'w') as f:
            f.write(f"// Generated by scripts/maps/{const.lower()}.py — edit the script, not this file.\n")
            f.write(f"export const {const}_LAYOUT: readonly string[] = [\n{body},\n];\n")

    def preview(self, path, spots=None, scale=12):
        img = Image.new('RGB', (self.cols * scale, self.rows * scale))
        d = ImageDraw.Draw(img)
        for y in range(self.rows):
            for x in range(self.cols):
                d.rectangle([x * scale, y * scale, (x + 1) * scale - 1, (y + 1) * scale - 1], fill=COLORS[self.g[y][x]])
        for x in range(0, self.cols, 5):
            d.line([x * scale, 0, x * scale, self.rows * scale], fill=(40, 40, 40))
            d.text((x * scale + 1, 1), str(x), fill=(255, 255, 0))
        for y in range(0, self.rows, 5):
            d.line([0, y * scale, self.cols * scale, y * scale], fill=(40, 40, 40))
            d.text((1, y * scale + 1), str(y), fill=(255, 255, 0))
        for name, (x, y) in (spots or {}).items():
            cx, cy = x * scale + scale // 2, y * scale + scale // 2
            d.ellipse([cx - 4, cy - 4, cx + 4, cy + 4], fill=(255, 255, 255))
            d.text((cx + 5, cy - 5), name, fill=(255, 255, 255))
        img.save(path)


def circle(c, cx, cy, radius, ch, only_on=None):
    """Fill a disc of tiles (optionally only replacing tiles in `only_on`)."""
    for y in range(cy - radius, cy + radius + 1):
        for x in range(cx - radius, cx + radius + 1):
            if (x - cx) ** 2 + (y - cy) ** 2 <= radius * radius + radius * 0.6:
                if 0 <= x < c.cols and 0 <= y < c.rows and (only_on is None or c.get(x, y) in only_on):
                    c.put(x, y, ch)


def ring(c, cx, cy, radius, ch):
    for y in range(cy - radius - 1, cy + radius + 2):
        for x in range(cx - radius - 1, cx + radius + 2):
            d2 = (x - cx) ** 2 + (y - cy) ** 2
            if radius * radius - radius <= d2 <= radius * radius + radius:
                c.put(x, y, ch)
